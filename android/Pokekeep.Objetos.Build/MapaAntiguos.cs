using System.Reflection;
using System.Text;
using PKHeX.Core;
using Pokekeep.Sprites;

namespace Pokekeep.Objetos.Build;

/// <summary>Una equivalencia: el objeto antiguo (id nativo, nombre) y el objeto moderno de PKHeX que es el mismo.</summary>
public sealed record Equivalencia(FamiliaAntigua Familia, int Nativo, string NombreAntiguo, int Moderno, string NombreModerno, string Via);

/// <summary>
/// Cruza los nombres ingleses de las listas antiguas de PKHeX (Gen. 1, 2, 3 y las de GameCube) con la lista moderna: un objeto antiguo sin id moderno en <c>ItemConverter</c> pero con un nombre que coincide
/// con EXACTAMENTE un objeto moderno (o con un renombrado verificado de <c>alias-modernos.tsv</c>) es el mismo objeto, y PKHeX ya tiene su sprite con el id moderno.
/// </summary>
public static class MapaAntiguos
{
    private static readonly (FamiliaAntigua Familia, EntityContext Ctx, GameVersion Version)[] Familias =
    [
        (FamiliaAntigua.Gen1, EntityContext.Gen1, GameVersion.RD),
        (FamiliaAntigua.Gen2, EntityContext.Gen2, GameVersion.GD),
        (FamiliaAntigua.Gen3, EntityContext.Gen3, GameVersion.FR),
        (FamiliaAntigua.Colosseum, EntityContext.Gen3, GameVersion.COLO),
        (FamiliaAntigua.XD, EntityContext.Gen3, GameVersion.XD),
    ];

    public static Dictionary<string, string> Alias()
    {
        using var s = Assembly.GetExecutingAssembly().GetManifestResourceStream("alias-modernos.tsv")!;
        using var r = new StreamReader(s, Encoding.UTF8);
        var d = new Dictionary<string, string>(StringComparer.Ordinal);
        _ = r.ReadLine();
        while (r.ReadLine() is { } l) { var v = l.Split('\t'); if (v.Length >= 2 && v[0].Length > 0) d[Fuente.Norm(v[0])] = Fuente.Norm(v[1]); }
        return d;
    }

    /// <summary>Las equivalencias de todas las familias y los objetos antiguos sin id moderno que NO se han podido igualar (con el motivo).</summary>
    public static (IReadOnlyList<Equivalencia> Equivalencias, IReadOnlyList<string> SinIgualar) Calcular(GameStrings ingles)
    {
        var alias = Alias();
        var modernos = new Dictionary<string, List<int>>(StringComparer.Ordinal);   // nombre normalizado -> ids modernos
        var lista = ingles.Item;
        for (var id = 1; id < lista.Count; id++)
        {
            if (string.IsNullOrWhiteSpace(lista[id])) continue;
            var n = Fuente.Norm(lista[id]);
            if (n.Length == 0) continue;
            if (!modernos.TryGetValue(n, out var l)) modernos[n] = l = [];
            l.Add(id);
        }
        var res = new List<Equivalencia>(); var sin = new List<string>();
        foreach (var (familia, ctx, version) in Familias)
        {
            var nombres = ingles.GetItemStrings(ctx, version);
            for (var nativo = 1; nativo < nombres.Length; nativo++)
            {
                var nombre = nombres[nativo];
                if (string.IsNullOrWhiteSpace(nombre) || nombre.All(c => c is '?' or ' ')) continue;
                if (familia != FamiliaAntigua.Gen1 && ItemConverter.GetItemDisplay(nativo, ctx) != ObjetosAntiguos.SinIdModerno) continue;   // Gen. 1: el id del Core no vale para la mochila, todo por nombre
                if (Maquinas.De(version, ctx, nativo) is not null) continue;   // las máquinas se resuelven por tipo, no por nombre
                var norm = Fuente.Norm(nombre);
                var via = "nombre";
                if (alias.TryGetValue(norm, out var renombrado)) { norm = renombrado; via = "renombrado"; }
                if (modernos.TryGetValue(norm, out var ids))
                {
                    // Varios objetos modernos con el mismo nombre (las copias de Leyendas: Arceus, id >= 1640, repiten Poké Ball, Poción...): el de id más bajo es el clásico.
                    var elegido = ids.Min();
                    res.Add(new Equivalencia(familia, nativo, nombre, elegido, lista[elegido], ids.Count == 1 ? via : via + " (el id más bajo de " + string.Join(",", ids) + ")"));
                }
                else
                    sin.Add($"{familia}\t{nativo}\t{nombre}\tningún objeto moderno se llama igual");
            }
        }
        return (res, sin);
    }

    /// <summary>El fichero fuente <c>ObjetosAntiguosTabla.cs</c> con las tablas (ordenadas por id nativo, para la búsqueda binaria).</summary>
    public static string GenerarFuente(IReadOnlyList<Equivalencia> equivalencias)
    {
        var sb = new StringBuilder();
        sb.Append("// <auto-generated>Generado por Pokekeep.Objetos.Build (mapa-antiguos) con las tablas de PKHeX.Core. No editar a mano: una prueba comprueba que coincide con lo que sale hoy del Core.</auto-generated>\n");
        sb.Append("namespace Pokekeep.Sprites;\n\npublic static partial class ObjetosAntiguos\n{\n");
        foreach (var (f, nombre) in new[] { (FamiliaAntigua.Gen1, "TablaGen1"), (FamiliaAntigua.Gen2, "TablaGen2"), (FamiliaAntigua.Gen3, "TablaGen3"), (FamiliaAntigua.Colosseum, "TablaColosseum"), (FamiliaAntigua.XD, "TablaXD") })
        {
            var filas = equivalencias.Where(e => e.Familia == f).OrderBy(e => e.Nativo).ToList();
            sb.Append($"    /// <summary>{filas.Count} equivalencias de {f}.</summary>\n    private static readonly Par[] {nombre} =\n    [\n");
            foreach (var e in filas) sb.Append($"        new({e.Nativo}, {e.Moderno}),   // {e.NombreAntiguo}{(e.Via == "renombrado" ? " (renombrado)" : "")} -> {e.NombreModerno}\n");
            sb.Append("    ];\n\n");
        }
        sb.Remove(sb.Length - 1, 1);
        sb.Append("}\n");
        return sb.ToString();
    }
}
